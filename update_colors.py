"""Regenerates the generated helper files:

- colors/colors.js: the list of texture swatches shown in the palette
- images-data.js: every picture embedded as a data URL. Only loaded by "Download picture (JPG)"
  when the page is opened straight from disk (file://), where browsers block reading the pictures.

Run:  python update_colors.py
Browsers can't list a folder on a static site, so run this after adding or removing
pictures (server.py also runs it on startup), then commit both generated files.
"""
import base64
import json
import mimetypes
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
COLORS_DIR = os.path.join(ROOT, 'colors')
MANIFEST = os.path.join(COLORS_DIR, 'colors.js')
IMAGES_DATA = os.path.join(ROOT, 'images-data.js')
IMAGE_EXTENSIONS = {'.jpg', '.jpeg', '.png', '.webp', '.gif'}


def list_images(folder):
    return sorted(
        (n for n in os.listdir(folder) if os.path.splitext(n)[1].lower() in IMAGE_EXTENSIONS),
        key=str.lower,
    )


def write_images_data(entries):
    lines = []
    for rel in entries:
        with open(os.path.join(ROOT, rel), 'rb') as f:
            encoded = base64.b64encode(f.read()).decode('ascii')
        mime = mimetypes.guess_type(rel)[0] or 'application/octet-stream'
        lines.append(f'  {json.dumps(rel)}: "data:{mime};base64,{encoded}"')
    text = '// Generated by update_colors.py - do not edit by hand\nconst embeddedImages = {\n' + ',\n'.join(lines) + '\n};\n'
    with open(IMAGES_DATA, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def update_colors():
    names = list_images(COLORS_DIR)
    text = '// Generated by update_colors.py - do not edit by hand\nconst colorTextures = ' + json.dumps(names, indent=2) + ';\n'
    with open(MANIFEST, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    write_images_data(list_images(ROOT) + [f'colors/{n}' for n in names])
    return names


if __name__ == '__main__':
    found = update_colors()
    print(f'colors/colors.js and images-data.js updated: {len(found)} texture(s)')
